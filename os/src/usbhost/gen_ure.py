"""gen_ure.py <if_ure.c> <out.inc> -- lift the RTL8152/8153 chip functions out of FreeBSD's if_ure.c, verbatim.

The driver's chip logic (register access over vendor control requests, the init / reset sequences, the RX filter, the
link status) is kept exactly as FreeBSD has it; phe_usb_ure.c supplies the few usb_ether / ifnet calls they make
(ure_ctl's uether_do_request, uether_pause, the ifnet flags) and does the transfers itself. The macros between the
includes and the first function (URE_SETBIT_*, the debug printfs) come along. Re-run after a FreeBSD import bump."""
import re, sys

FUNCS = """ure_ctl ure_read_mem ure_write_mem ure_read_1 ure_read_2 ure_read_4 ure_write_1 ure_write_2 ure_write_4
ure_ocp_reg_read ure_ocp_reg_write ure_sram_write ure_read_chipver ure_attach_post ure_init ure_rxfilter ure_reset
ure_get_link_status ure_rtl8152_init ure_rtl8152_nic_reset ure_rtl8153_init ure_rtl8153b_init ure_rtl8153b_nic_reset
ure_disable_teredo ure_enable_aldps ure_phy_status ure_stop""".split()

src = open(sys.argv[1], newline='').read().split('\n')
out = ["/* GENERATED by gen_ure.py from FreeBSD sys/dev/usb/net/if_ure.c (the import's pin) -- do not edit.",
       " * The code below is FreeBSD's, under the licence at the top of if_ure.c: */", ""]
# the licence block, verbatim
i = 0
while not src[i].startswith(' */'):
    out.append(src[i]); i += 1
out += [src[i], ""]
# the file's macros: URE_SETBIT_* / URE_CLRBIT_* (multi-line #defines)
for k, l in enumerate(src):
    if re.match(r'#define\s+URE_(SET|CLR)BIT_\d', l):
        out.append(l); j = k
        while src[j].endswith(chr(92)):
            j += 1; out.append(src[j])
out.append("")
protos, bodies = [], []
for f in FUNCS:
    k = next((n for n, l in enumerate(src) if l.startswith(f + '(')), None)
    if k is None:
        sys.exit("gen_ure: %s not found" % f)
    e = next(n for n in range(k, len(src)) if src[n] == '}')
    head = src[k - 1].strip()
    if not head.startswith('static'):
        head = 'static ' + head
    sig = src[k]; n = k
    while not sig.rstrip().endswith(')'):
        n += 1; sig += ' ' + src[n].strip()
    protos.append(head + ' ' + sig + ';')
    bodies += [head, *src[k:e + 1], ""]
out += protos + [""] + bodies
open(sys.argv[2], 'w', newline='\n').write('\n'.join(out))
